# -*- coding: utf-8 -*-
"""Build out/view/manifest.json -- the data file the viewer app loads.

Sources, in order of authority:
  1. out/plan.csv            header/record survey of the WHOLE corpus (all files)
  2. out/export/index*.csv   what the export actually did (status, png counts)
  3. a scan of out/export    which NPCs really have PNGs on disk right now

    python mkview.py                     # -> out/view/manifest.json
"""
import argparse
import collections
import csv
import glob
import json
import os
import re
import time

HERE = os.path.dirname(os.path.abspath(__file__))


def frame_key(name):
    """First-frame order: direction 1 frame 0 first, then frame order."""
    m = re.match(r'd(\d+)_(\d+)\.png$', name)
    if m:
        return (int(m.group(1)), int(m.group(2)), name)
    m = re.match(r'f(\d+)\.png$', name)
    if m:
        return (0, int(m.group(1)), name)
    return (10 ** 9, 10 ** 9, name)


def rows_of(pattern, key='file'):
    seen = {}
    for p in sorted(glob.glob(pattern)):
        with open(p, newline='', encoding='utf-8') as fh:
            for r in csv.DictReader(fh):
                seen[r[key]] = r
    return seen


def iv(v):
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return 0


def scan_export(root):
    """stem -> (png count, png bytes, name of the FIRST frame file on disk).

    The first frame is the true first frame: some files start a direction with
    a pixel-less frame, so d1_000.png can be absent and the folder's first
    image is then d1_001.png (or f0001.png).
    """
    out = {}
    if not os.path.isdir(root):
        return out
    with os.scandir(root) as it:
        for e in it:
            if not e.is_dir():
                continue
            n = b = 0
            first = fk = None
            with os.scandir(e.path) as it2:
                for f in it2:
                    if not f.name.endswith('.png'):
                        continue
                    n += 1
                    try:
                        b += f.stat().st_size
                    except OSError:
                        pass
                    k = frame_key(f.name)
                    if fk is None or k < fk:
                        fk, first = k, f.name
            out[e.name] = (n, b, first)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--plan', default=os.path.join(HERE, 'out', 'plan.csv'))
    ap.add_argument('--export', default=os.path.join(HERE, 'out', 'export'))
    ap.add_argument('--out', default=os.path.join(HERE, 'out', 'view'))
    a = ap.parse_args()

    plan = rows_of(a.plan)
    idx = rows_of(os.path.join(a.export, 'index*.csv'))
    disk = scan_export(a.export)
    print(f'plan rows={len(plan)} export rows={len(idx)} exported dirs={len(disk)}')

    entries = []
    for name, p in plan.items():
        stem = name[:-4] if name.endswith('.gsn') else name
        i = idx.get(name)
        ist = i['status'] if i else ''
        # An export verdict only overrides the plan when it is 'ok' or
        # 'partial'. A stale 'fail' must not win: plan.csv is regenerated by
        # the current parser, which now reads the 4-byte/pixel family.
        st = ist if ist in ('ok', 'partial') else p['status']
        k = iv(p['skipped'])
        f = iv(p['frames'])
        if st == 'ok' and f and k == f:
            st = 'empty'                     # anchor-only: every frame has no pixels
        dirs = [int(x) for x in (p['dirs'] or '').split('|') if x.strip()]
        e = {'n': stem, 'v': p['version'], 's': iv(p['size']), 'f': f, 'k': k,
             'o': iv(p['oh']), 'p': iv(p['first_px']), 'd': dirs,
             'st': st, 'm': (i or p)['method']}
        d = disk.get(stem)
        if d:
            e['c'], e['b'], f0 = d
            if f0:
                e['f0'] = f0                    # the real first frame on disk
        if st == 'fail' and d:
            st = e['st'] = 'partial'          # lenient export wrote frames anyway
        err = (i['err'] if ist in ('ok', 'partial') and i['err'] else p['err']) or ''
        if err:
            e['e'] = err[:200]
        entries.append(e)

    entries.sort(key=lambda e: e['n'])
    st = collections.Counter(e['st'] for e in entries)
    tot = {'files': len(entries),
           'frames': sum(e['f'] for e in entries if e['st'] != 'fail'),
           'pngs': sum(e.get('c', 0) for e in entries),
           'bytes': sum(e.get('b', 0) for e in entries),
           'px_bytes': sum(iv(p['px_bytes']) for p in plan.values()),
           'status': dict(st),
           'generated': time.strftime('%Y-%m-%d %H:%M:%S'),
           'upstream': os.path.dirname(HERE)}
    os.makedirs(a.out, exist_ok=True)
    p = os.path.join(a.out, 'manifest.json')
    with open(p, 'w', encoding='utf-8') as fh:
        json.dump({'totals': tot, 'entries': entries}, fh,
                  ensure_ascii=False, separators=(',', ':'))
    print(f'wrote {p}  {os.path.getsize(p) / 2**20:.2f} MiB')
    print('status: ' + '  '.join(f'{k}={v}' for k, v in sorted(st.items())))
    print(f"frames={tot['frames']} pngs={tot['pngs']} png={tot['bytes'] / 2**30:.2f} GiB")


if __name__ == '__main__':
    main()
